def _rect_props(rects, rho=7850):
    """矩形集合 -> (A, I1, I2, W1, W2, mass_kg_m)
    矩形 (x0,y0,x1,y1)，坐标单位 mm。"""
    A = 0.0
    cx = cy = 0.0
    parts = []
    for (x0, y0, x1, y1) in rects:
        w = abs(x1 - x0)
        h = abs(y1 - y0)
        a = w * h
        xc = (x0 + x1) / 2
        yc = (y0 + y1) / 2
        A += a
        cx += a * xc
        cy += a * yc
        parts.append((a, xc, yc, w, h))
    cx /= A
    cy /= A
    Ixx = Iyy = 0.0
    for (a, xc, yc, w, h) in parts:
        Ixx += w * h ** 3 / 12 + a * (yc - cy) ** 2
        Iyy += h * w ** 3 / 12 + a * (xc - cx) ** 2
    I1, I2 = (Ixx, Iyy) if Ixx >= Iyy else (Iyy, Ixx)
    # 抵抗矩：按各轴最远纤维距离（矩形分解近似）
    maxy = max(max(abs(y0 - cy), abs(y1 - cy)) for (x0, y0, x1, y1) in rects)
    maxx = max(max(abs(x0 - cx), abs(x1 - cx)) for (x0, y0, x1, y1) in rects)
    W1 = I1 / max(maxx, maxy) if max(maxx, maxy) > 0 else 0
    W2 = I2 / min(maxx, maxy) if min(maxx, maxy) > 0 else 0
    mass = A * rho / 1e6
    return A, I1, I2, W1, W2, mass


def _channel_rects(h, b, c, t):
    """C型钢（卷边槽钢）矩形分解：腹板 + 两翼缘 + 两卷边。"""
    rects = [
        (0, -h / 2, t, h / 2),                    # 腹板
        (t, h / 2 - t, t + b, h / 2),             # 上翼缘
        (t, -h / 2, t + b, -h / 2 + t),           # 下翼缘
        (t + b, h / 2 - t, t + b + c, h / 2),     # 上卷边
        (t + b, -h / 2, t + b + c, -h / 2 + t),   # 下卷边
    ]
    return rects


def _z_rects(h, b, c, t):
    """Z型钢矩形分解（斜边简化）：腹板 + 两翼缘反向 + 两卷边。"""
    rects = [
        (0, -h / 2, t, h / 2),
        (t, h / 2 - t, t + b, h / 2),
        (t - c, -h / 2, t, -h / 2 + t),
        (t + b + c, h / 2 - t, t + b, h / 2),
        (t - c + c, -h / 2, t - c + c + c, -h / 2 + t),
    ]
    return rects


def _u_rects(h, b, c, t):
    """U型钢（无卷边或卷边朝内）：腹板 + 两翼缘 + 两卷边朝内。"""
    rects = [
        (0, -h / 2, t, h / 2),
        (t, h / 2 - t, t + b, h / 2),
        (t, -h / 2, t + b, -h / 2 + t),
        (t + b, h / 2 - t, t + b + c, h / 2),
        (t + b, -h / 2, t + b + c, -h / 2 + t),
    ]
    return rects


def _angle_rects(b, t):
    """等肢角钢矩形分解：两肢。"""
    return [
        (0, 0, t, b),
        (t, 0, b, t),
    ]


def _tube_rects(h, b, t):
    """矩形/方形管矩形分解：四壁。"""
    return [
        (0, 0, b, t),
        (0, h - t, b, h),
        (0, t, t, h - t),
        (b - t, t, b, h - t),
    ]


def get_props(spec, model):
    """返回截面属性 dict；未知型号返回 None。"""
    if spec == "自定义":
        return None
    for name, dims in SECTIONS.get(spec, []):
        if name == model:
            break
    else:
        return None

    if spec == "C型钢":
        A, I1, I2, W1, W2, m = _rect_props(_channel_rects(*dims))
    elif spec == "Z型钢":
        A, I1, I2, W1, W2, m = _rect_props(_z_rects(*dims))
    elif spec == "U型钢":
        A, I1, I2, W1, W2, m = _rect_props(_u_rects(*dims))
    elif spec == "槽钢":
        gb = CHANNEL_GB.get(dims)
        if not gb:
            return None
        A_cm2, Ix, Iy, Wx, Wy = gb
        A = A_cm2 * 100
        I1, I2 = Ix * 1e4, Iy * 1e4
        W1, W2 = Wx * 1e3, Wy * 1e3
        m = A * 7850 / 1e6
    elif spec == "角钢":
        A, I1, I2, W1, W2, m = _rect_props(_angle_rects(*dims))
    elif spec in ("方钢管", "矩形钢管"):
        h, b, t = dims
        A, I1, I2, W1, W2, m = _rect_props(_tube_rects(h, b, t))
    elif spec == "圆钢/圆管":
        if len(dims) == 1:                      # 圆钢
            D = dims[0]
            A = math.pi * D ** 2 / 4
            I = math.pi * D ** 4 / 64
            W = math.pi * D ** 3 / 32
            I1 = I2 = I
            W1 = W2 = W
        else:                                   # 圆管
            D, t = dims
            Di = D - 2 * t
            A = math.pi * (D ** 2 - Di ** 2) / 4
            I = math.pi * (D ** 4 - Di ** 4) / 64
            W = 2 * I / D
            I1 = I2 = I
            W1 = W2 = W
        m = A * 7850 / 1e6
    else:
        return None
    return {
        "spec": spec, "model": model,
        "A": A, "I1": I1, "I2": I2, "W1": W1, "W2": W2,
        "mass": m,
    }


